// 改图提示词模板。
//
// 为什么模板要写这么长：给模型的指令只写「把背景去掉」，模型就会
// 自由发挥——输出一张尺寸不对、格式不对、还把原图覆盖了的图。
// 模板必须把**主体约束 / 技术约束 / 输出路径 / 原图只读**四件事写全，
// 模型才有确定的目标。
//
// 落盘纪律：产物一律是同目录下的新文件 `<原名>.ai.<扩展名>`，
// 原图只读——这条同时写进每个模板，模型自己会照做，用户也不必盯。

export interface AiPromptTemplate {
  id: string;
  /** 按钮上的短标签。 */
  label: string;
  /** 悬停说明：这个模板会做什么。 */
  hint: string;
  /** 生成完整提示词。file 是文件名，out 是建议的输出文件名。 */
  build: (file: string, out: string) => string;
}

/** 产物文件名：photo.png → photo.ai.png（扩展名之前插入 .ai）。 */
export function aiOutputName(fileName: string): string {
  const dot = fileName.lastIndexOf(".");
  if (dot <= 0) return `${fileName}.ai`;
  return `${fileName.slice(0, dot)}.ai${fileName.slice(dot)}`;
}

/** 每个模板都带的两条底线：原图只读 + 产物落盘到新文件。 */
const TAIL = (out: string) => `
【硬约束】
- 原图只读：禁止修改、覆盖、移动或删除原文件，所有处理都在副本上进行。
- 产物写到原文件同目录下的新文件「${out}」，并在回复里给出该文件的完整路径。
- 完成后用一句话说明你做了什么，不要重复贴大段过程。`;

