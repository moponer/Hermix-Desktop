/** 「加入 AI 对话」的开场指令：先看、先说，别动手。 */
export function joinConversationPrompt(fileName: string): string {
  return `请先读一下「${fileName}」，用两三句话说明它是什么、里面装了什么、是否值得我细看。读完先别动手改任何文件，等我具体要求。`;
}

